import { el } from "./dom.js";
import { t } from "./i18n.js";
import * as S from "./state.js";
import { openReferencePreview } from "./reference-preview.js";

const emptyText = (reason) => reason === "generated"
  ? t("The source is generated by an earlier pass and is not available in this preview.")
  : reason === "unbound"
  ? t("This tag has no binding in the current pass.")
  : t("No reference file is attached to this tag.");

function handlePill(handle) {
  return el("span", { class: "mmc-compiled-tag-handle", text: `@${handle}`,
    style: { "--tag": `var(--mmc-tag-${S.tagIndex(handle)})` } });
}

/** Only the compiler's current-pass mapping is shown; ordinal labels do not
 *  resolve against the timeline pool or against another pass's media. */
export function openCompiledTagPreview(binding, { returnFocus = null, onClose = null } = {}) {
  const handles = [...new Set(binding.handles ?? [])];
  const current = el("div", { class: "mmc-compiled-tag-values" });
  const currentRow = el("div", { class: "mmc-compiled-tag-meta-row", hidden: true }, [
    el("span", { class: "mmc-compiled-tag-key", text: t("Current reference") }), current,
  ]);
  const files = binding.assets ?? [];
  const sourceNote = el("p", { class: "mmc-compiled-tag-note",
    text: t("Source file preview — model-side processing is not simulated.") });
  const details = el("div", { class: "mmc-compiled-tag-details" }, [
    el("div", { class: "mmc-compiled-tag-meta-row" }, [
      el("span", { class: "mmc-compiled-tag-key", text: t("Model tag") }),
      el("span", { class: "mmc-compiled-tag-label", text: binding.label,
        style: { "--tag": `var(--mmc-tag-${S.tagIndex(handles[0] ?? binding.label)})` } }),
    ]),
    handles.length && el("div", { class: "mmc-compiled-tag-meta-row" }, [
      el("span", { class: "mmc-compiled-tag-key", text: t("Connected handles") }),
      el("div", { class: "mmc-compiled-tag-values" }, handles.map(handlePill)),
    ]),
    currentRow,
    files.length && sourceNote,
  ]);
  return openReferencePreview(files, {
    caption: t("Preview {tag}", { tag: binding.label }), returnFocus, onClose,
    includeAudio: true, details, originalImages: true, emptyMessage: emptyText(binding.reason),
    onShow: (asset) => {
      current.replaceChildren(...(asset.handle ? [handlePill(asset.handle)] : []));
      currentRow.hidden = !asset.handle;
      const notes = [t("Source file preview — model-side processing is not simulated.")];
      if (asset.parent_handle) notes.push(t("This reference is a panel of @{handle}; the original source image is shown.",
        { handle: asset.parent_handle }));
      if (asset.replacement_origin) notes.push(t("This image is a captured frame from a source video."));
      sourceNote.textContent = notes.join(" ");
    },
  });
}
