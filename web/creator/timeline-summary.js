import { el } from "./dom.js";
import { t } from "./i18n.js";
import { rulesFor } from "./canvas.js";
import * as S from "./state.js";

/** The same run facts on the Timeline and the node face, from the piece's own metrics. */
export function timelineSummary(piece) {
  const seconds = S.timelineSeconds(piece);
  const frames = S.timelineFrames(piece);
  const auto = S.hasAutoDuration(piece);
  const rules = rulesFor(S.pieceFamily(piece));
  const totalTenths = Math.max(0, Math.round(seconds * 10));
  const totalSeconds = totalTenths / 10;
  const minutes = Math.floor(totalTenths / 600);
  const remainder = (totalTenths % 600) / 10;
  const humanTime = minutes
    ? t("{minutes} min {seconds} sec", { minutes, seconds: remainder })
    : t("{seconds} sec", { seconds: totalSeconds });
  return el("div", { class: "mmc-tl-total" }, [
    el("div", {
      class: "mmc-tl-summary-pill mmc-tl-summary-full",
      ...(auto ? { title: t("An estimate: a shot on auto is measured by the model "
                          + "while it renders, so the finished length is not known "
                          + "until it has.") } : {}),
    }, [
      el("span", { text: t("Full video") }),
      el("span", { class: "mmc-tl-summary-time", text: `${auto ? "~" : ""}${humanTime}` }),
      el("span", { class: "mmc-tl-summary-frames",
        text: `(${auto ? "~" : ""}${t("{fps} fps · {frames} frames", {
          fps: rules.fps, frames: frames.toLocaleString("en-US"),
        })})` }),
    ]),
    el("div", { class: "mmc-tl-summary-pill mmc-tl-summary-new",
      title: t("Video duration generated by this run, not waiting time. Includes every current generated target."),
    }, [
      el("span", { text: t("New video") }),
      el("b", { class: "mmc-tl-next", text: t("{seconds} sec", {
        seconds: S.sampledSeconds(piece).toFixed(1),
      }) }),
    ]),
    el("div", { class: "mmc-tl-summary-pill mmc-tl-summary-cards",
      text: t("Cards {count}", { count: piece.segments.length }) }),
  ]);
}

/** A separator belongs between adjacent pills, not at the start of a wrapped row. */
export function observeTimelineSummary(summary) {
  const fit = () => {
    const groups = [...summary.querySelectorAll(".mmc-tl-summary-pill")];
    groups.forEach((group, index) => group.classList.toggle("row-start",
      index === 0 || group.offsetTop !== groups[index - 1].offsetTop));
  };
  const observer = new ResizeObserver(fit);
  observer.observe(summary);
  fit();
  return observer;
}
