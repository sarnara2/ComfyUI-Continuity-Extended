export const SHEET_LOCALES = Object.freeze(Object.fromEntries(
  ["ko", "ja", "zh"].map((language, index) => [language,
    Object.freeze(Object.fromEntries(Object.entries(ROWS).map(([key, values]) => [key, values[index]]))),
  ]),
));

export function sheetLocale() {
  let language;
  try { language = globalThis.app?.extensionManager?.setting?.get?.("Comfy.Locale"); }
  catch { language = null; }
  language ||= (typeof navigator !== "undefined" && navigator.language) || "en";
  return SHEET_LOCALES[language] ? language : (SHEET_LOCALES[language.split("-")[0]] ? language.split("-")[0] : "en");
}

export function st(text, params) {
  const translated = SHEET_LOCALES[sheetLocale()]?.[text] ?? t(text);
  if (!params) return translated;
  return translated.replace(/\{(\w+)\}/g, (slot, name) =>
    Object.hasOwn(params, name) ? String(params[name]) : slot);
}
